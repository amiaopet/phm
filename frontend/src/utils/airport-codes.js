/**
 * 根据机场三字代码获取中文名称
 * @param {string} code 机场三字代码
 * @returns {string} 机场中文名称，若未找到则返回原代码
 */
export const getAirportName = (code) => {
  if (!code) return '';
  return airportCodeMap[code] || code;
}

/**
 * 格式化机场显示名称
 * @param {string} code 机场三字代码或中文名称
 * @returns {string} 格式化后的机场名称
 */
export const formatAirportName = (code) => {
  if (!code) return '';
  return getAirportName(code);
}

/**
 * 根据中文名称或部分中文名称查找机场代码
 * @param {string} keyword 中文关键词
 * @returns {Array} 符合条件的机场列表，包含代码和名称
 */
export const searchAirportByName = (keyword) => {
  if (!keyword) return [];

  const results = [];
  for (const [code, name] of Object.entries(airportCodeMap)) {
    if (name.includes(keyword) || code === keyword.toUpperCase()) {
      results.push({
        code,
        name,
        display: `${code} - ${name}`
      });
    }
  }
  return results;
}

/**
 * 获取所有机场列表，用于下拉选择
 * @returns {Array} 机场列表，包含代码和名称
 */
export const getAllAirports = () => {
  const airports = [];
  for (const [code, name] of Object.entries(airportCodeMap)) {
    airports.push({
      code,
      name,
      display: `${code} - ${name}`
    });
  }
  return airports;
} 